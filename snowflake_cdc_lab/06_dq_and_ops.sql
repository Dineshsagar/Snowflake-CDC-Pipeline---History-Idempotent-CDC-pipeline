CREATE OR REPLACE TABLE UTIL.DQ_RESULTS (
    RUN_TS     TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    TEST_NAME  VARCHAR,
    TARGET     VARCHAR,
    FAIL_COUNT NUMBER,
    STATUS     VARCHAR
);

/* Every data quality test is the same shape:
   a SELECT that returns the ROWS THAT BREAK THE RULE. Zero rows = pass.
   That is literally all a dbt test compiles to. */

CREATE OR REPLACE PROCEDURE UTIL.SP_RUN_DQ()
RETURNS STRING LANGUAGE SQL AS
$$
BEGIN
  -- unique PK
  INSERT INTO UTIL.DQ_RESULTS (TEST_NAME, TARGET, FAIL_COUNT, STATUS)
  SELECT 'unique_booking_id', 'SILVER.BOOKING', COUNT(*), IFF(COUNT(*)=0,'PASS','FAIL')
  FROM (SELECT BOOKING_ID FROM SILVER.BOOKING GROUP BY 1 HAVING COUNT(*)>1);

  -- not null PK
  INSERT INTO UTIL.DQ_RESULTS (TEST_NAME, TARGET, FAIL_COUNT, STATUS)
  SELECT 'not_null_booking_id', 'SILVER.BOOKING', COUNT(*), IFF(COUNT(*)=0,'PASS','FAIL')
  FROM SILVER.BOOKING WHERE BOOKING_ID IS NULL;

  -- accepted values
  INSERT INTO UTIL.DQ_RESULTS (TEST_NAME, TARGET, FAIL_COUNT, STATUS)
  SELECT 'accepted_booking_status', 'SILVER.BOOKING', COUNT(*), IFF(COUNT(*)=0,'PASS','FAIL')
  FROM SILVER.BOOKING WHERE BOOKING_STATUS NOT IN ('CONFIRMED','PENDING','CANCELLED');

  -- referential integrity
  INSERT INTO UTIL.DQ_RESULTS (TEST_NAME, TARGET, FAIL_COUNT, STATUS)
  SELECT 'fk_claim_to_booking', 'SILVER.CLAIM', COUNT(*), IFF(COUNT(*)=0,'PASS','FAIL')
  FROM SILVER.CLAIM c
  LEFT JOIN SILVER.BOOKING b ON b.BOOKING_ID = c.BOOKING_ID
  WHERE b.BOOKING_ID IS NULL AND NOT c.IS_DELETED;

  -- business rule
  INSERT INTO UTIL.DQ_RESULTS (TEST_NAME, TARGET, FAIL_COUNT, STATUS)
  SELECT 'net_revenue_not_negative', 'GOLD.BOOKING_FACT', COUNT(*), IFF(COUNT(*)=0,'PASS','WARN')
  FROM GOLD.BOOKING_FACT WHERE NET_REVENUE < 0;

  -- reconciliation: no cancelled/deleted booking may reach GOLD
  INSERT INTO UTIL.DQ_RESULTS (TEST_NAME, TARGET, FAIL_COUNT, STATUS)
  SELECT 'gold_excludes_cancelled', 'GOLD.BOOKING_FACT', COUNT(*), IFF(COUNT(*)=0,'PASS','FAIL')
  FROM GOLD.BOOKING_FACT g
  JOIN SILVER.BOOKING s ON s.BOOKING_ID = g.BOOKING_ID
  WHERE s.IS_DELETED OR s.BOOKING_STATUS = 'CANCELLED';

  RETURN 'DQ complete';
END;
$$;

CALL UTIL.SP_RUN_DQ();
