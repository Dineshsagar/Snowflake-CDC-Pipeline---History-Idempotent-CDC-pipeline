-- Freshness / SLA
CREATE OR REPLACE VIEW UTIL.V_FRESHNESS AS
SELECT 'SILVER.BOOKING' AS obj, MAX(UPDATED_AT) AS last_update,
       DATEDIFF('minute', MAX(UPDATED_AT), CURRENT_TIMESTAMP()) AS lag_min
FROM SILVER.BOOKING
UNION ALL
SELECT 'GOLD.BOOKING_FACT', MAX(LOAD_TS),
       DATEDIFF('minute', MAX(LOAD_TS), CURRENT_TIMESTAMP())
FROM GOLD.BOOKING_FACT;

SELECT * FROM UTIL.V_FRESHNESS;


